import type { Player } from "./types";

const profile = (slug: string, code: string) =>
  `https://www.stockholmopen.se/en/players/${slug}/${code}`;

function player(
  partial: Omit<Player, "country" | "bio" | "birthplace"> & {
    countrySv: string;
    countryEn: string;
    birthplaceSv?: string;
    birthplaceEn?: string;
    sv: string;
    en: string;
  },
): Player {
  const {
    countrySv,
    countryEn,
    birthplaceSv,
    birthplaceEn,
    sv,
    en,
    ...rest
  } = partial;
  return {
    ...rest,
    country: { sv: countrySv, en: countryEn },
    birthplace:
      birthplaceSv && birthplaceEn
        ? { sv: birthplaceSv, en: birthplaceEn }
        : undefined,
    bio: { sv, en },
  };
}

