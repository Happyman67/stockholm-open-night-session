function singles(id: string): Side {
  const player = playersById.get(id);
  if (!player) throw new Error(`Missing player ${id}`);
  return {
    members: [
      {
        name: `${player.first} ${player.last}`,
        playerId: id,
        country: player.country,
      },
    ],
    seed: player.seed,
    entry: player.entry,
  };
}

function pair(
  members: PairMember[],
  extra?: { seed?: number; entry?: Side["entry"] },
): Side {
  return { members, seed: extra?.seed, entry: extra?.entry };
}

